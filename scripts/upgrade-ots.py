#!/usr/bin/env python3
"""Upgrade the OpenTimestamps proofs attached to lnd GitHub releases.

The proofs (*.ots) are uploaded right after stamping, when they only hold
pending attestations: promises by the calendar servers to commit the stamp to
Bitcoin. Once a calendar has done so, `ots upgrade` can fetch the path to the
Bitcoin block header. From then on the proof can be verified with a Bitcoin
node alone, even if the calendars disappear.

This script only reads from GitHub. It upgrades the proofs of the published
releases that aren't complete yet, verifies each upgraded proof against the
release file it timestamps, and writes the results to a new directory:

  upload.sh             replaces the proofs on the releases, using gh
  summary.txt           what was upgraded, what is still pending, errors
  <tag>/<file>.ots      upgraded proof
  <tag>/<file>.ots.bak  original proof, as downloaded from the release
  <tag>/<file>          the release file the proof timestamps

The directory is only written if at least one proof was upgraded.

Requires Python 3.9 or later, and the ots client (opentimestamps-client) in
PATH.
"""

import argparse
import collections
import datetime
import hashlib
import http.client
import http.server
import itertools
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
import textwrap
import threading
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

GITHUB_API = "https://api.github.com"
USER_AGENT = "lnd-upgrade-ots"

# Timeout in seconds for requests to GitHub.
HTTP_TIMEOUT = 60

# Timeout in seconds for an ots command. ots itself doesn't limit how long it
# waits for a calendar server.
OTS_TIMEOUT = 300

# Tags and asset names end up in upload.sh, so only plain ones are accepted.
SAFE_NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9._+-]*")

# What ots verify prints when it can't use the Bitcoin node at all. That would
# fail every proof, so the run stops.
NODE_PROBLEMS = ("Could not connect to", "non-JSON HTTP response")

# How ots upgrade ends, and shows a calendar's answer, for a stamp that isn't
# in a Bitcoin block yet. A proof is only pending with both: without the first,
# ots failed, maybe after a calendar answered.
UPGRADE_INCOMPLETE = "Failed! Timestamp not complete"
PENDING_ANSWER = re.compile(
    r"^Calendar \S+: (Pending confirmation|Timestamped by transaction)",
    re.MULTILINE)

# The errors of a failed HTTP request. A response that ends early raises
# IncompleteRead, which isn't an OSError.
NETWORK_ERRORS = (OSError, http.client.HTTPException)

UPGRADED = "upgraded"
COMPLETE = "already complete"
PENDING = "pending"
ERROR = "ERROR"

# What happened to one proof. asset_id is the ID of the release asset.
Result = collections.namedtuple("Result", "tag name status detail asset_id")

UPLOAD_SH = r"""#!/bin/bash
#
# Generated by upgrade-ots.py at {time} UTC.
#
{intro}
#
#   ots verify {example}
#
{backend}
#
# This script can be run again: a proof is only replaced while the release
# still has the exact asset it was upgraded from, and proofs that were
# already uploaded are skipped.

set -euo pipefail
cd "$(dirname "$0")"
{warning}
REPO={repo_sh}

# replace uploads $tag/$name to the release, replacing the asset with ID
# $old_id. $sha256 is the checksum of the upgraded proof.
replace() {{
    local tag=$1 old_id=$2 name=$3 sha256=$4
    local current

    # The ID and digest of the release asset with this name, if there is one.
    current=$(gh api "repos/$REPO/releases/tags/$tag" \
        --jq ".assets[] | select(.name == \"$name\") | \"\(.id) \(.digest)\"")

    case $current in
    *" sha256:$sha256")
        echo "$tag: $name is already uploaded"
        return
        ;;
    "$old_id "*)
        # Delete by ID: if someone replaced the proof in the meantime, this
        # fails instead of deleting their upload.
        gh api --method DELETE "repos/$REPO/releases/assets/$old_id" --silent
        ;;
    "")
        # An earlier run stopped between deleting the old proof and
        # uploading the new one.
        ;;
    *)
        echo "ERROR: $tag: $name changed on the release since it was" \
            "downloaded, not replacing it" >&2
        exit 1
        ;;
    esac

    # Without --clobber, this fails instead of replacing a proof that someone
    # uploaded since the old one was deleted.
    gh release upload "$tag" "$tag/$name" --repo "$REPO"
    echo "$tag: uploaded $name"
}}

{replacements}
"""


class ProofError(Exception):
    """A problem with one proof. It is reported, and the run goes on."""


class NodeError(Exception):
    """The Bitcoin node can't be used, which stops the run."""


class RpcError(Exception):
    """An error returned to ots by EsploraProxy."""

    def __init__(self, code, message):
        super().__init__(message)
        self.code = code


class Ots:
    """Runs the ots client."""

    def __init__(self, bitcoin_node):
        self.options = ["--no-cache"]
        if bitcoin_node:
            self.options += ["--bitcoin-node", bitcoin_node]

    def run(self, command, *args):
        """Returns the exit status and the output of an ots command. The
        status is None if the command timed out."""
        argv = ["ots", *self.options, command, *map(str, args)]

        # ots prints the time of an attestation in the local time zone.
        env = dict(os.environ, TZ="UTC")
        try:
            done = subprocess.run(argv, capture_output=True, text=True,
                                  env=env, timeout=OTS_TIMEOUT)
        except subprocess.TimeoutExpired:
            return None, f"ots {command} timed out after {OTS_TIMEOUT} seconds"
        return done.returncode, done.stdout + done.stderr

    def is_complete(self, proof):
        """Reports whether the proof is anchored in a Bitcoin block. That's
        also how ots decides whether a proof is complete."""
        status, output = self.run("info", proof)
        if status != 0:
            raise ProofError("not a valid proof:\n" + indent(tidy(output)))
        return "BitcoinBlockHeaderAttestation(" in output


class EsploraProxy:
    """Answers the bitcoind RPC calls that ots verify makes (getblockcount,
    getblockhash and getblockheader) with data from an Esplora API, such as
    https://mempool.space/api. It listens on a free local port."""

    def __init__(self, api_url):
        self.api_url = api_url.rstrip("/")
        self.cache = {}
        proxy = self

        class Handler(http.server.BaseHTTPRequestHandler):
            protocol_version = "HTTP/1.1"

            def do_POST(self):
                length = int(self.headers["Content-Length"])
                request = json.loads(self.rfile.read(length))
                body = json.dumps(proxy.handle(request)).encode()
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)

            def log_message(self, *args):
                pass

        self.server = http.server.ThreadingHTTPServer(
            ("127.0.0.1", 0), Handler)
        threading.Thread(target=self.server.serve_forever, daemon=True).start()

    @property
    def url(self):
        """The URL to pass to ots --bitcoin-node."""
        host, port = self.server.server_address[:2]
        return f"http://{host}:{port}"

    def handle(self, request):
        """Returns the JSON-RPC response to a request."""
        result = error = None
        try:
            result = self.call(request["method"], request["params"])
        except RpcError as e:
            error = {"code": e.code, "message": str(e)}
        except (*NETWORK_ERRORS, ValueError) as e:
            error = {"code": -1, "message": f"{self.api_url}: {e}"}
        return {"result": result, "error": error, "id": request.get("id")}

    def call(self, method, params):
        if method == "getblockcount":
            return int(self.get("blocks/tip/height"))

        if method == "getblockhash":
            try:
                return self.get(f"block-height/{int(params[0])}")
            except urllib.error.HTTPError as e:
                if e.code != 404:
                    raise
                # What bitcoind answers for a height it doesn't have.
                raise RpcError(-8, "Block height out of range") from e

        if method == "getblockheader":
            block_hash = params[0]
            header = self.get(f"block/{block_hash}/header")
            raw = bytes.fromhex(header)
            if len(raw) != 80 or sha256d(raw)[::-1].hex() != block_hash:
                raise RpcError(-1, f"{self.api_url} returned a header that "
                                   f"isn't the one of block {block_hash}")
            return header

        raise RpcError(-32601, "Method not found")

    def get(self, path):
        """Returns the response to an API request, as text. With a retry, it
        still answers within the 30 seconds ots waits."""
        if path not in self.cache:
            body = fetch(f"{self.api_url}/{path}", timeout=12)
            self.cache[path] = body.decode().strip()
        return self.cache[path]


def sha256d(data):
    return hashlib.sha256(hashlib.sha256(data).digest()).digest()


def sha256_file(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def indent(text):
    return textwrap.indent(text.strip(), "    ")


def tidy(output):
    """Shortens the output of a failed ots command: ots repeats an error for
    each attestation, and a crash only needs its last line."""
    lines = output.strip().splitlines()
    if "Traceback (most recent call last):" in lines:
        lines = lines[-1:]
    return "\n".join(dict.fromkeys(lines))


def comment(text):
    """Returns the text as a shell comment."""
    return textwrap.indent(textwrap.fill(text, 76), "# ")


def plural(n, noun):
    return f"{n} {noun}" + ("" if n == 1 else "s")


def without_credentials(url):
    parts = urllib.parse.urlsplit(url)
    return parts._replace(netloc=parts.netloc.rpartition("@")[2]).geturl()


def fetch(url, headers=None, timeout=HTTP_TIMEOUT):
    """Returns the body of the response to a GET request. A network error or
    a server error is retried once."""
    request = urllib.request.Request(
        url, headers={"User-Agent": USER_AGENT, **(headers or {})})
    for retry in (True, False):
        try:
            with urllib.request.urlopen(request, timeout=timeout) as r:
                return r.read()
        except urllib.error.HTTPError as e:
            if e.code < 500 or not retry:
                raise
        except NETWORK_ERRORS:
            if not retry:
                raise
        time.sleep(2)


def list_releases(repo):
    """Returns all releases of the repository, newest first."""
    releases = []
    for page in itertools.count(1):
        batch = json.loads(fetch(
            f"{GITHUB_API}/repos/{repo}/releases?per_page=100&page={page}",
            {"Accept": "application/vnd.github+json"}))
        if not batch:
            return releases
        releases += batch


def download(asset, directory):
    """Saves a release asset in the directory and returns its path."""
    path = directory / asset["name"]
    try:
        path.write_bytes(fetch(asset["browser_download_url"]))
    except NETWORK_ERRORS as e:
        raise ProofError(f"can't download {asset['name']}: {e}") from e
    return path


def process(release, asset, work_dir, ots, max_pending_days):
    """Upgrades and verifies one proof. Leaves the upgraded proof, the
    original (.bak) and the file it timestamps in work_dir/<tag>.

    Returns the status of the proof and a description."""
    tag, name = release["tag_name"], asset["name"]
    for value in (tag, name):
        if not SAFE_NAME.fullmatch(value):
            raise ProofError(f"unexpected characters in {value!r}")

    directory = work_dir / tag
    directory.mkdir(exist_ok=True)
    proof = download(asset, directory)
    if ots.is_complete(proof):
        return COMPLETE, ""
    original = sha256_file(proof)

    # This fails as long as no calendar has committed the stamp to Bitcoin,
    # which is checked below.
    status, output = ots.run("upgrade", proof)
    if status is None:
        raise ProofError(output)

    if not ots.is_complete(proof):
        ended = status == 1 and output.strip().endswith(UPGRADE_INCOMPLETE)
        if not ended or not PENDING_ANSWER.search(output):
            raise ProofError(f"ots upgrade failed (exit status {status}):\n"
                             + indent(tidy(output)))
        uploaded = datetime.datetime.strptime(
            asset["created_at"], "%Y-%m-%dT%H:%M:%S%z")
        age = (datetime.datetime.now(datetime.timezone.utc) - uploaded).days
        if age > max_pending_days:
            raise ProofError(f"still pending after {age} days")
        return PENDING, f"uploaded {age} days ago"

    backup = directory / (name + ".bak")
    if not backup.is_file() or sha256_file(backup) != original:
        raise ProofError("ots upgrade didn't keep the original as .bak")

    # A proof timestamps the release file with the same name minus .ots. That
    # can't be a proof or a backup, whose names this script uses itself.
    target_name = name[:-len(".ots")]
    if target_name.endswith((".ots", ".bak")):
        raise ProofError(f"timestamps {target_name}, which isn't supported")
    target = [a for a in release["assets"] if a["name"] == target_name]
    if not target:
        raise ProofError(f"no {target_name} on the release to verify against")
    target_path = download(target[0], directory)

    status, output = ots.run("verify", "-f", target_path, proof)
    if status != 0:
        if any(problem in output for problem in NODE_PROBLEMS):
            raise NodeError(tidy(output))
        raise ProofError("verification failed:\n" + indent(tidy(output)))

    match = re.search(r"Bitcoin block (\d+) attests existence as of (\S+)",
                      output)
    return UPGRADED, f"Bitcoin block {match[1]}, {match[2]}" if match else ""


def write_upload_sh(out, repo, upgraded, started, backend, esplora):
    replacements = []
    for r in upgraded:
        sha256 = sha256_file(out / r.tag / r.name)
        replacements.append(shlex.join(
            ["replace", r.tag, str(r.asset_id), r.name, sha256]))

    intro = (f"Replaces {plural(len(upgraded), 'OpenTimestamps proof')} on "
             f"the releases of {repo} with the upgraded ones in this "
             f"directory. The originals are kept next to them as .ots.bak. "
             f"Each upgraded proof was verified against the file it "
             f"timestamps, which is here as well. To check one again:")

    warning = ""
    if esplora:
        warning = "\necho {} \\\n    {} >&2\n".format(
            shlex.quote("WARNING: these proofs were verified against block "
                        "headers from"),
            shlex.quote(f"{esplora}, not from a Bitcoin node."))

    path = out / "upload.sh"
    path.write_text(UPLOAD_SH.format(
        time=f"{started:%Y-%m-%d %H:%M}",
        intro=comment(intro),
        repo_sh=shlex.quote(repo),
        example=f"{upgraded[0].tag}/{upgraded[0].name}",
        backend=comment(backend),
        warning=warning,
        replacements="\n".join(replacements),
    ))
    path.chmod(0o755)


def count(results):
    """Returns a line with the number of proofs by status."""
    counts = collections.Counter(r.status for r in results)
    return (f"{plural(len(results), 'proof')}: {counts[UPGRADED]} upgraded, "
            f"{counts[COMPLETE]} already complete, {counts[PENDING]} "
            f"pending, {plural(counts[ERROR], 'error')}.")


def summarize(results, heading):
    """Returns a report of the results, starting with the heading lines."""
    lines = heading + ["", count(results)]
    for status, title in ((UPGRADED, "Upgraded"), (PENDING, "Pending"),
                          (ERROR, "Errors")):
        selected = [r for r in results if r.status == status]
        if selected:
            lines += ["", f"{title}:"]
        for r in selected:
            lines.append(f"  {r.tag}/{r.name}: "
                         + r.detail.replace("\n", "\n  "))
    return "\n".join(lines) + "\n"


def parse_args():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "tags", nargs="*",
        help="the releases to look at (default: all published releases)")
    parser.add_argument(
        "--repo", default="lightningnetwork/lnd",
        help="GitHub repository (default: %(default)s)")
    parser.add_argument(
        "--out", type=Path, metavar="DIR",
        help="output directory, which must not exist yet "
             "(default: ./ots-upgrade-<UTC time>)")
    node = parser.add_mutually_exclusive_group()
    node.add_argument(
        "--bitcoin-node", metavar="URL",
        help="bitcoind RPC URL, such as http://user:pass@127.0.0.1:8332 "
             "(default: ots reads the local bitcoin.conf). "
             "A pruned node is enough.")
    node.add_argument(
        "--esplora", metavar="URL",
        help="for testing without a node, get block headers from an Esplora "
             "API instead of bitcoind, trusting that server: "
             "--esplora=https://mempool.space/api")
    parser.add_argument(
        "--max-pending-days", type=int, default=3, metavar="DAYS",
        help="report proofs that are still pending after this many days as "
             "errors (default: %(default)s)")

    args = parser.parse_args()
    if args.esplora and urllib.parse.urlsplit(
            args.esplora).scheme not in ("http", "https"):
        parser.error("--esplora needs an http:// or https:// URL")
    return args


def main():
    args = parse_args()
    if shutil.which("ots") is None:
        sys.exit("ERROR: ots (opentimestamps-client) isn't in PATH")

    started = datetime.datetime.now(datetime.timezone.utc)
    out = args.out or Path(f"ots-upgrade-{started:%Y%m%dT%H%M%SZ}")
    if out.exists():
        sys.exit(f"ERROR: {out} already exists")

    bitcoin_node = args.bitcoin_node
    if args.esplora:
        bitcoin_node = EsploraProxy(args.esplora).url
        backend = (f"WARNING: block headers came from {args.esplora}, not "
                   "from a Bitcoin node, so the proofs were only verified "
                   "as far as that server can be trusted.")
        print(f"WARNING: verifying proofs against block headers from "
              f"{args.esplora}. This trusts that server to serve the real "
              f"Bitcoin chain. Use your own node (the default) for proofs "
              f"you publish.", file=sys.stderr)
    elif bitcoin_node:
        backend = ("Block headers came from bitcoind at "
                   f"{without_credentials(bitcoin_node)}.")
    else:
        backend = "Block headers came from the local bitcoind."
    ots = Ots(bitcoin_node)

    try:
        releases = [r for r in list_releases(args.repo) if not r["draft"]]
    except (*NETWORK_ERRORS, ValueError) as e:
        sys.exit(f"ERROR: can't list the releases of {args.repo}: {e}")

    if args.tags:
        known = {r["tag_name"] for r in releases}
        unknown = [tag for tag in args.tags if tag not in known]
        if unknown:
            sys.exit(f"ERROR: {args.repo} has no published release "
                     f"{', '.join(unknown)}")
        releases = [r for r in releases if r["tag_name"] in args.tags]

    proofs = [(r, a) for r in releases for a in r["assets"]
              if a["name"].endswith(".ots")]
    print(f"Checking {plural(len(proofs), 'proof')} of "
          f"{plural(len(releases), 'release')} of {args.repo}.", flush=True)

    results = []
    with tempfile.TemporaryDirectory(prefix="upgrade-ots-") as work:
        work_dir = Path(work)
        for release, asset in proofs:
            try:
                status, detail = process(release, asset, work_dir, ots,
                                         args.max_pending_days)
            except ProofError as e:
                status, detail = ERROR, str(e)
            except NodeError as e:
                sys.exit(f"ERROR: ots can't use the Bitcoin node:\n"
                         f"{indent(str(e))}\nPass --bitcoin-node=URL, or "
                         f"--esplora=https://mempool.space/api to test "
                         f"without a node.")
            r = Result(release["tag_name"], asset["name"], status, detail,
                       asset["id"])
            results.append(r)
            line = f"{r.tag}: {r.name}: {r.status}"
            print(f"{line}: {r.detail}" if r.detail else line, flush=True)

        upgraded = [r for r in results if r.status == UPGRADED]
        if upgraded:
            out.mkdir(parents=True)
            for r in upgraded:
                (out / r.tag).mkdir(exist_ok=True)
                for name in (r.name, r.name + ".bak", r.name[:-len(".ots")]):
                    shutil.move(str(work_dir / r.tag / name),
                                str(out / r.tag / name))

            releases_line = "all published releases"
            if args.tags:
                releases_line = ", ".join(args.tags)
            heading = [
                f"Checked the proofs of {args.repo} ({releases_line}) at "
                f"{started:%Y-%m-%d %H:%M} UTC.",
                backend,
            ]
            (out / "summary.txt").write_text(summarize(results, heading))
            write_upload_sh(out, args.repo, upgraded, started, backend,
                            args.esplora)

    print()
    print(count(results))
    if upgraded:
        print(f"Wrote {out}. Review it, then run {out / 'upload.sh'} to "
              f"replace the proofs on GitHub.")
    else:
        print("Nothing to upload.")

    if any(r.status == ERROR for r in results):
        sys.exit(1)


if __name__ == "__main__":
    main()
